function toTitleCase(str) {
  return str.toLowerCase().split(' ').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

function parseData() {
  const lines = rawPdfPages.trim().split('\n');
  const records = [];
  let headerSkipped = false;

  for (let rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;
    if (line.startsWith('Class Section')) continue; // Header row

    // Match columns: Class (1), Section (2), Roll_No (3), then Student_Name (variable length words),
    // then 6 subject marks (English, Hindi, Maths, EVS, GK, Computer),
    // then Total_Score, Percentage, Grade, Attendance_Status
    const tokens = line.split(/\s+/);
    if (tokens.length < 13) continue;

    const studentClass = tokens[0];
    const section = tokens[1];
    const rollCode = tokens[2];
    const numericRoll = parseInt(rollCode.split('/')[0], 10);

    // End tokens: [English, Hindi, Maths, EVS, GK, Computer, Total_Score, Percentage, Grade, Attendance_Status] = 10 tokens
    const endTokens = tokens.slice(-10);
    const nameTokens = tokens.slice(3, tokens.length - 10);
    const rawName = nameTokens.join(' ');
    const name = toTitleCase(rawName);

    const [engStr, hinStr, matStr, evsStr, gkStr, compStr, totalStr, percStr, gradeStr, attStr] = endTokens;

    const parseMark = (m) => m === 'AB' ? 0 : parseInt(m, 10);

    const eng = parseMark(engStr);
    const hin = parseMark(hinStr);
    const mat = parseMark(matStr);
    const evs = parseMark(evsStr);
    const gk = parseMark(gkStr);
    const comp = parseMark(compStr);

    let attPerc = 90;
    if (attStr === 'Absent') attPerc = 0;
    else if (attStr === 'Partial') attPerc = 65;

    const studentId = 'CCS-' + studentClass + section + '-' + rollCode;

    const record = {
      student_id: studentId,
      name: name,
      class: studentClass,
      section: section,
      roll_no: numericRoll,
      roll_code: rollCode,
      exam_name: 'Annual Evaluation 2025-26',
      session: '2025-2026',
      attendance_percentage: attPerc,
      marks: {
        'English': eng,
        'Hindi': hin,
        'Mathematics': mat,
        'EVS': evs,
        'GK': gk,
        'Computer': comp
      },
      max_marks: {
        'English': 80,
        'Hindi': 80,
        'Mathematics': 80,
        'EVS': 80,
        'GK': 80,
        'Computer': 80
      }
    };

    records.push(record);
  }

  return records;
}

