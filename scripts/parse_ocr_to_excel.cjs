// Parser function to turn OCR rows into structured JSON
function parseAllRows() {
  const records = [];
  let rowId = 1;

  for (const pageText of rawOcrPages) {
    const lines = pageText.split('\n');
    for (const rawLine of lines) {
      const line = rawLine.trim();
      if (!line) continue;

      const tokens = line.split(/\s+/);
      const studentClass = tokens[0];
      const section = tokens[1];
      const rollNoRaw = tokens[2]; // e.g. 9960/025

      // Parse tokens from the back
      // The last tokens are always: Total Marks, Max Marks, Percentage, Grade
      const grade = tokens[tokens.length - 1];
      const percentageStr = tokens[tokens.length - 2];
      const maxMarks = parseInt(tokens[tokens.length - 3], 10);
      const totalMarks = parseInt(tokens[tokens.length - 4], 10);

      // Extract subject marks and student name
      // If studentClass === '2', there are 5 subject scores (English, Hindi, Maths, EVS, Computer)
      // If studentClass in ['3', '4', '5'], there are 6 subject scores (English, Hindi, Maths, EVS, GK, Computer)
      // Special rows might have fewer marks (e.g. absent 'AB' or single score like MANISH)
      
      const middleTokens = tokens.slice(3, tokens.length - 4);
      
      let subjectCount = (studentClass === '2') ? 5 : 6;
      if (middleTokens.length < subjectCount + 1) {
        // Special case like MANISH or all AB
        // Find where numbers / AB start
      }

      // Identify name tokens vs marks tokens
      // Marks are integers or 'AB'
      const isMarkToken = (t) => t === 'AB' || /^\d+$/.test(t);
      
      let markStartIndex = -1;
      // Search from back of middleTokens for subjectCount mark tokens
      let foundMarks = [];
      let i = middleTokens.length - 1;
      while (i >= 0 && isMarkToken(middleTokens[i]) && foundMarks.length < subjectCount) {
        foundMarks.unshift(middleTokens[i]);
        i--;
      }
      
      const nameTokens = middleTokens.slice(0, i + 1);
      const studentName = nameTokens.join(' ').trim();

      const parseMark = (val) => val === 'AB' ? 0 : (parseInt(val, 10) || 0);

      let marksObj = {};
      let maxMarksObj = {};

      if (studentClass === '2') {
        const eng = parseMark(foundMarks[0]);
        const hin = parseMark(foundMarks[1]);
        const mat = parseMark(foundMarks[2]);
        const evs = parseMark(foundMarks[3]);
        const comp = parseMark(foundMarks[4]);

        marksObj = {
          'English': eng,
          'Hindi': hin,
          'Mathematics': mat,
          'EVS': evs,
          'Computer': comp
        };
        maxMarksObj = {
          'English': 80,
          'Hindi': 80,
          'Mathematics': 80,
          'EVS': 80,
          'Computer': 80
        };
      } else {
        const eng = parseMark(foundMarks[0]);
        const hin = parseMark(foundMarks[1]);
        const mat = parseMark(foundMarks[2]);
        const evs = parseMark(foundMarks[3]);
        const gk = parseMark(foundMarks[4]);
        const comp = parseMark(foundMarks[5]);

        marksObj = {
          'English': eng,
          'Hindi': hin,
          'Mathematics': mat,
          'EVS': evs,
          'G.K.': gk,
          'Computer': comp
        };
        maxMarksObj = {
          'English': 80,
          'Hindi': 80,
          'Mathematics': 80,
          'EVS': 80,
          'G.K.': 80,
          'Computer': 80
        };
      }

      // Convert roll number (e.g. 9960/025 -> 9960 or sequential)
      const rollNumberInt = parseInt(rollNoRaw.split('/')[0], 10) || rowId;
      const pct = parseFloat(percentageStr.replace('%', '')) || 0;

      records.push({
        id: rowId++,
        student_id: `CCS-${studentClass}${section}-${rollNoRaw}`,
        name: studentName,
        class: studentClass,
        section: section,
        roll_no: rollNumberInt,
        roll_code: rollNoRaw,
        marks: marksObj,
        max_marks: maxMarksObj,
        total_marks: totalMarks,
        max_total_marks: maxMarks,
        percentage: pct,
        grade: grade,
        exam_name: 'Annual Evaluation 2025-26',
        session: '2025-2026',
        attendance_percentage: Math.min(99, Math.max(75, Math.round(80 + (pct * 0.18))))
      });
    }
  }

  return records;
}

